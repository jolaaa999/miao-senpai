"""回复长度纪律：系统提示词最末的那一段。

为什么要单独一块，而且必须放在最末：

1. 原来的人设里写着「答疑目标 400~1500 字」。她照做了——不是话痨，
   是**规则让她写这么长**。群里问一句 GitHub 怎么入门，她回三段小作文。
2. 一条规则埋在几千字人设的第 108 行，实际权重极低。模型对最后读到的
   内容最敏感，所以长度约束得挪到提示词末尾才压得住。

2026-10-25 大改：从「给数字预算」改成「给节奏」。
原因：数字（60 字）确实压住了长度，但它压出的是**判词**——模型把
「先反应、再解释、最后一句点题」整段写出来，出站截断砍掉前后只留最后那句，
发出来就是「这一刀就变得很致命：绩点是软排序，德育线是硬门槛」。
这比长更像机器。人不是被截断出来的，是本来就说这么点。
所以这里改成描述节奏（一句、几个字、想说的分几次说），
数字只作参照，不再当唯一目标。
"""

from __future__ import annotations

# 内容刻意写得像「怎么说人话」，而不是「输出限制」：
# 后者会让模型转向 obedient-assistant 腔，反而更假。
_BREVITY_HINT = """【这一条发多长】

按真人发微信的数来，别按写文档来：
- 默认就一句话，常常只有两三个字。多打一个字都是浪费。
- 被问正经问题时：一句话结论 + 最多一条理由，然后停。想要细节的人会追问。
- 只有对方明确说「详细讲讲」「给个步骤」「看不懂」才展开，展开就分点、一点一行。
- 想说的多，先说最要紧那句，剩下的等对方问。
- 不写结语、不写总结句、不写过渡句、不列选项清单、不解释自己为什么这么答。

（这段只管长度和节奏：该查的还是要查、工具照常用，只是别把查到的写成报告。）"""


# 语气铁律，同样放在最末。为什么不能只留在人设里：
# 【共情的分寸】那段人设里写得很清楚，连「今天好累」都当例子点名了，
# 实测照样被当成情绪求助。规则在人设中段＝权重极低，位置比措辞重要。
_TONE_HINT = """【别演】

- 日常吐槽（好累、作业多、没过线、被骂了）**不是**情绪求助：顺着吐槽、给个建议、或者干脆不接，别转成安慰模式。
- 不写「抱抱」「心疼你」「辛苦了」「你已经很努力了」这种安慰套话，也不要每句结尾都鼓励。
- 不打客服腔：「有什么需要帮忙的」「随时叫我」「希望能帮到你」——群里没人这么说话。
- 不点评自己说的话：不写「这句我接不上」「你这条信息不全」「这句话没有前文」，也不复述对方原话再解释。
- 不写复盘报告：「说实话，我刚才的回答确实偏了，抱歉，翻回去看……」——真错了就一句「行，我搞错了」，然后接着聊。
- 不给判词：「A 是 B，C 是 D」这种一句到底的结论句，是评论员，不是聊天。"""


def build_brevity_hint(enabled: bool = True) -> str:
    """返回长度纪律文本；关掉时返回空串（调用方据此跳过注入）。"""
    if not enabled:
        return ""
    return _BREVITY_HINT + "\n\n" + _TONE_HINT


def brevity_hint_text() -> str:
    """给测试/诊断用：不管开关，直接拿原文（含语气铁律）。"""
    return _BREVITY_HINT + "\n\n" + _TONE_HINT
