"""回复长度纪律：系统提示词最末的那一段。

为什么要单独一块，而且必须放在最末：

1. 原来的人设里写着「答疑目标 400~1500 字」。她照做了——不是话痨，
   是**规则让她写这么长**。群里问一句 GitHub 怎么入门，她回三段小作文。
2. 一条规则埋在几千字人设的第 108 行，实际权重极低。模型对最后读到的
   内容最敏感，所以长度约束得挪到提示词末尾才压得住。

2026-10-25 大改：从「给数字预算」改成「给节奏」。
原因：数字（60 字）确实压住了长度，但它压出的是**判词**——模型把
「先反应、再解释、最后一句点题」整段写出来，出站截断砍掉前后只留最后那句，
发出来就是「这一刀就变得很致命：绩点是软排序，德育线是硬门槛」。
这比长更像机器。人不是被截断出来的，是本来就说这么点。

2026-10-26 再改：拆成「闲聊档」和「解释档」两套。
原因：只有一套规则时，模型自己判断「这条该不该展开」，它几乎总判「该」，
实测最近 159 条回复中位数 63 字、77% 超过 40 字，而真人聊天在 10~20 字。
正经解释长一点没问题（用户明确这么说），问题是日常闲聊也被拉成三段式。
所以这里分两档，由 is_explain_request() 用代码判定场景——
把「要不要展开」的权力从模型手里拿回来。
"""

from __future__ import annotations

import re

# 「这句是在要解释」的信号词。命中就给解释档，否则一律按闲聊压短。
# 刻意只收明确的求知/动手意图：漏判的代价是回答短一点（可以追问），
# 误判的代价是日常闲聊又变回小作文（用户抱怨过的那个）。
_EXPLAIN_RE = re.compile(
    r"怎么|怎么弄|怎样|为什么|为啥|啥是|什么是|是什么|什么意思|啥意思|怎么办|"
    r"步骤|流程|教我|帮我写|帮我改|帮我做|详细|展开|讲讲|说说|解释一下|"
    r"教程|方案|对比|查一下|搜一下|介绍一下|推荐|报错|怎么解决|怎么配置"
)


def is_explain_request(text: str) -> bool:
    """这句是「要一个解释」，还是闲聊？

    为什么用代码判而不是让模型自判：模型几乎总觉得自己该多给点，
    实测「活人味不足」的根因就在这里——判断权在它手上，而它偏向长。
    空文本按闲聊处理（只有触发词、没有内容的场景不该展开）。
    """
    return bool(_EXPLAIN_RE.search(str(text or "")))


# 闲聊档。内容刻意写得像「怎么说人话」，而不是「输出限制」：
# 后者会让模型转向 obedient-assistant 腔，反而更假。
_BREVITY_HINT_CHAT = """【这一条发多长】

按真人发微信的数来，别按写文档来：
- 一句话，20 字以内。常常只有两三个字。
- 只发一条，不追着补第二条解释。
- 不要「接住 + 解释 + 再补一刀」的三段式：吐槽完就停，解释和补充等对方追问。
- 不写结语、不写总结句、不点题、不列选项清单、不解释自己为什么这么答。

（这段只管长度和节奏：该查的还是要查、工具照常用，只是别把查到的写成报告。）"""

# 解释档：对方明确要一个答案时才用。允许长，但结构不能被拉成文档。
_BREVITY_HINT_EXPLAIN = """【这条对方是在问正经问题】

允许写长，但按「结论 → 理由 → 需要才分点」来，不要铺排：
- 第一句就给结论，别先铺垫背景。
- 最多跟一条最关键的理由；要步骤/对比/代码才分点，一点一行。
- 400 字以内。写完就停，不写结语、不总结、不「希望这些对你有帮助」。

（该查的还是要查，工具照常用。）"""

# 语气铁律，两档共用。为什么不能只留在人设里：
# 【共情的分寸】那段人设里写得很清楚，连「今天好累」都当例子点名了，
# 实测照样被当成情绪求助。规则在人设中段＝权重极低，位置比措辞重要。
_TONE_HINT = """【别演】

- 日常吐槽（好累、作业多、没过线、被骂了）**不是**情绪求助：顺着吐槽、给个建议、或者干脆不接，别转成安慰模式。
- 不写「抱抱」「心疼你」「辛苦了」「你已经很努力了」这种安慰套话，也不要每句结尾都鼓励。
- 不打客服腔：「有什么需要帮忙的」「随时叫我」「希望能帮到你」——群里没人这么说话。
- 不点评自己说的话：不写「这句我接不上」「你这条信息不全」「这句话没有前文」，也不复述对方原话再解释。
- 不写复盘报告：「说实话，我刚才的回答确实偏了，抱歉，翻回去看……」——真错了就一句「行，我搞错了」，然后接着聊。
- 不给判词：「A 是 B，C 是 D」这种一句到底的结论句，是评论员，不是聊天。"""


def build_brevity_hint(enabled: bool = True, *, explain: bool = False) -> str:
    """返回长度纪律文本；关掉时返回空串（调用方据此跳过注入）。

    explain 由调用方用 is_explain_request() 判断后传入：
    解释档允许展开，闲聊档压到一句话。
    """
    if not enabled:
        return ""
    head = _BREVITY_HINT_EXPLAIN if explain else _BREVITY_HINT_CHAT
    return head + "\n\n" + _TONE_HINT


def brevity_hint_text() -> str:
    """给测试/诊断用：不管开关、不分档，直接拿全部原文。"""
    return _BREVITY_HINT_CHAT + "\n\n" + _BREVITY_HINT_EXPLAIN + "\n\n" + _TONE_HINT
