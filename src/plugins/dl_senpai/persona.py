def format_fewshot_block(pairs: tuple[tuple[str, str], ...] | None = None) -> str:
    """拼「接话原则」块。

    参数 pairs 留着只为兼容旧调用：就算传进来也不再当台词用，
    字面样例这条路已经封了（见上面 FEWSHOT_DIALOGUES 的注释）。
    """
    lines = [FEWSHOT_SYSTEM_EXTRA.strip()]
    lines.extend(f"- {item}" for item in REPLY_PRINCIPLES)
    if EXCEPTION_SAMPLES:
        lines.append(_EXCEPTION_INTRO)
        for user, assistant in EXCEPTION_SAMPLES:
            lines.append(f"群友：{user}　学姐：{assistant}")
    return chr(10).join(lines)


